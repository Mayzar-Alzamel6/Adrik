// Spreads the coach's shared code from this project (the source of truth) to its two other homes:
//   - ../adrik-mobile: src/lib/ai/coach.ts and its test, copied verbatim;
//   - supabase/functions/coach: coach.ts + the safety kit it needs, with Deno-style ".ts" import specifiers.
//
//   node scripts/copy-coach.mjs           write the copies
//   node scripts/copy-coach.mjs --check   only report copies that are out of date (exit 1 if any)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const mobile = resolve(here, "../adrik-mobile");
const check = process.argv.includes("--check");
const read = (p) => readFileSync(p, "utf8");
const GENERATED = "// Generated by scripts/copy-coach.mjs from adrik-personal/";

/** [target path, expected content] */
const outputs = [];
const fn = (name, from, rewrite = (s) => s) =>
  outputs.push([join(here, "supabase/functions/coach", name), `${GENERATED}${from}: do not edit here.\n${rewrite(read(join(here, from)))}`]);

fn("coach.ts", "src/lib/ai/coach.ts", (s) => s.replace('from "../safety/analysis"', 'from "./analysis.ts"'));
fn("analysis.ts", "src/lib/safety/analysis.ts", (s) => s.replace('from "./crisis-detector"', 'from "./crisis-detector.ts"'));
fn("crisis-detector.ts", "src/lib/safety/crisis-detector.ts");

if (existsSync(join(mobile, "package.json"))) {
  for (const file of ["src/lib/ai/coach.ts", "tests/coach.test.mjs"]) outputs.push([join(mobile, file), read(join(here, file))]);
} else {
  console.warn("adrik-mobile not found next to this project: only the function copies are handled.");
}

let stale = 0;
for (const [to, content] of outputs) {
  if (existsSync(to) && read(to) === content) continue;
  stale++;
  const label = to.replace(resolve(here, ".."), "..");
  if (check) {
    console.log(`${existsSync(to) ? "differs" : "missing"}  ${label}`);
  } else {
    mkdirSync(dirname(to), { recursive: true });
    writeFileSync(to, content);
    console.log(`wrote    ${label}`);
  }
}
// Every import specifier must have been rewritten, or Deno can't load the function.
for (const [to, content] of outputs.filter(([p]) => p.includes("supabase"))) {
  for (const m of content.matchAll(/from "(\.[^"]+)"/g)) {
    if (!m[1].endsWith(".ts")) {
      console.error(`unrewritten import ${m[1]} in ${to}`);
      process.exit(1);
    }
  }
}
console.log(stale ? `${stale} cop${stale === 1 ? "y" : "ies"} ${check ? "out of date" : "written"}.` : "Coach copies are identical.");
if (check && stale) process.exit(1);
